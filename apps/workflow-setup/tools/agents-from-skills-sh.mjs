#!/usr/bin/env node
// Writes agents.toml from the agent table of skills.sh (`npx skills`), with
// the changes in agents.overrides.json. Each override has a `reason`, which
// goes into agents.toml as a comment, and replaces the fields it names.
//
//   node tools/agents-from-skills-sh.mjs [path/to/skills/dist/cli.mjs] > agents.toml
//
// Without a path, it takes the newest skills package in the npx cache.
// The table is plain data in the minified CLI. This script cuts it out and
// runs it in a sandbox where the home folder is "/HOME", no file exists,
// and no environment variable is set. Thus each path is the default path.

import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, posix } from "node:path";
import vm from "node:vm";

const OVERRIDES = JSON.parse(readFileSync(new URL("../agents.overrides.json", import.meta.url), "utf8"));
const FIELDS = ["project", "global", "kind", "aliases"];

function newestCli() {
  const root = join(homedir(), ".npm/_npx");
  const found = readdirSync(root)
    .map((dir) => join(root, dir, "node_modules/skills/dist/cli.mjs"))
    .filter((file) => existsSync(file))
    .sort((a, b) => statSync(b).mtimeMs - statSync(a).mtimeMs);
  if (found.length === 0) throw new Error("no skills package in ~/.npm/_npx. Run `npx skills --help` once, or give the path.");
  return found[0];
}

function closingBrace(text, open) {
  let depth = 0;
  for (let i = open; i < text.length; i++) {
    if (text[i] === "{") depth++;
    if (text[i] === "}" && --depth === 0) return i;
  }
  throw new Error("the agent table has no end");
}

const cli = process.argv[2] ?? newestCli();
const text = readFileSync(cli, "utf8");
const version = JSON.parse(readFileSync(join(dirname(cli), "../package.json"), "utf8")).version;

const start = text.indexOf("const home = homedir();");
const table = text.indexOf("const agents = {");
if (start < 0 || table < start) throw new Error(`${cli}: the agent table is not where this script expects it`);
const source = text.slice(start, closingBrace(text, table + "const agents = ".length) + 1) + ";\nglobalThis.result = agents;";

const sandbox = {
  homedir: () => "/HOME",
  join: posix.join,
  xdgConfig: undefined,
  existsSync: () => false,
  readFileSync: () => {
    throw new Error("no file");
  },
  process: { env: {}, cwd: () => "/CWD", platform: "darwin" },
};
vm.runInNewContext(source, sandbox);
const agents = Object.values(sandbox.result).sort((a, b) => a.name.localeCompare(b.name));

const quote = (value) => JSON.stringify(value);
const lines = [
  `# Generated by tools/agents-from-skills-sh.mjs from skills ${version}. Do not edit by hand.`,
  "# Each table is one agent: its skill folder in a project and in the home folder.",
  "# Override: lines mark the changes from agents.overrides.json.",
  "# kind: claude-plugin and codex-plugin install whole plugins. Without kind,",
  "# the agent gets one link per skill.",
];
for (const [name, override] of Object.entries(OVERRIDES)) {
  if (!agents.some((agent) => agent.name === name)) throw new Error(`agents.overrides.json: skills ${version} has no agent ${name}`);
  if (!override.reason) throw new Error(`agents.overrides.json: ${name} has no reason`);
  const unknown = Object.keys(override).filter((key) => key !== "reason" && !FIELDS.includes(key));
  if (unknown.length > 0) throw new Error(`agents.overrides.json: ${name} has unknown fields ${unknown.join(", ")}`);
}
for (const agent of agents) {
  if (agent.skillsDir.startsWith("/")) throw new Error(`${agent.name}: the project folder is not relative`);
  if (agent.globalSkillsDir !== undefined && !agent.globalSkillsDir.startsWith("/HOME/")) throw new Error(`${agent.name}: the global folder is not in the home folder`);
  const { reason, ...override } = OVERRIDES[agent.name] ?? {};
  const fields = {
    project: agent.skillsDir,
    global: agent.globalSkillsDir?.replace(/^\/HOME\//, "~/"),
    ...override,
  };
  lines.push("");
  if (reason) lines.push(`# Override: ${reason}`);
  lines.push(`[${quote(agent.name)}]`, `display = ${quote(agent.displayName)}`);
  for (const key of FIELDS) {
    const value = fields[key];
    if (value === undefined || (Array.isArray(value) && value.length === 0)) continue;
    lines.push(`${key} = ${Array.isArray(value) ? `[${value.map(quote).join(", ")}]` : quote(value)}`);
  }
}
process.stdout.write(lines.join("\n") + "\n");
